revoke all on function public.attendance_for_token(text) from public,anon,authenticated;
revoke all on function public.attendance_submit(text,uuid,text) from public,anon,authenticated;
revoke all on function public.attendance_overview() from public,anon,authenticated;
revoke all on function public.audit_driver_points() from public,anon,authenticated;
grant execute on function public.admin_rotate_attendance_link(uuid,text,timestamptz) to authenticated;
grant execute on function public.admin_revoke_attendance_link(uuid) to authenticated;
grant execute on function public.attendance_for_token(text) to anon,authenticated;
