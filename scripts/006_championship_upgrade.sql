-- Run in Supabase SQL Editor. Additive migration: does not change stored points/results/ratings.
create table if not exists public.attendance_links (
 driver_id uuid primary key references public.drivers(id) on delete cascade,
 token_hash text not null unique check(token_hash ~ '^[a-f0-9]{64}$'),
 created_at timestamptz not null default now(),
 expires_at timestamptz not null,
 revoked_at timestamptz
);
create table if not exists public.attendance_entries (
 race_id uuid not null references public.races(id) on delete cascade,
 driver_id uuid not null references public.drivers(id) on delete cascade,
 choice text not null check(choice in ('yes','maybe','no')),
 updated_at timestamptz not null default now(),
 primary key(race_id,driver_id)
);
create table if not exists public.points_changes (
 id bigint generated always as identity primary key,
 driver_id uuid not null references public.drivers(id) on delete cascade,
 old_points int not null,
 new_points int not null,
 changed_by uuid,
 changed_at timestamptz not null default now()
);
create or replace function public.audit_driver_points() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
 if new.points is distinct from old.points then
  insert into public.points_changes(driver_id,old_points,new_points,changed_by)
  values(new.id,old.points,new.points,auth.uid());
 end if;
 return new;
end; $$;
drop trigger if exists driver_points_audit on public.drivers;
create trigger driver_points_audit after update of points on public.drivers
for each row execute function public.audit_driver_points();

alter table public.attendance_links enable row level security;
alter table public.attendance_entries enable row level security;
alter table public.points_changes enable row level security;
drop policy if exists attendance_links_admin_read on public.attendance_links;
create policy attendance_links_admin_read on public.attendance_links for select to authenticated using ((select public.is_admin()));
drop policy if exists attendance_entries_admin_all on public.attendance_entries;
create policy attendance_entries_admin_all on public.attendance_entries for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists points_changes_admin_read on public.points_changes;
create policy points_changes_admin_read on public.points_changes for select to authenticated using ((select public.is_admin()));

-- Tokens generated by Node.js crypto.randomBytes(32), only SHA-256 hashes are stored.
create or replace function public.admin_rotate_attendance_link(p_driver_id uuid,p_token_hash text,p_expires_at timestamptz)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
 if not public.is_admin() then return false; end if;
 if p_token_hash !~ '^[a-f0-9]{64}$' or p_expires_at <= now() or p_expires_at > now()+interval '370 days' then return false; end if;
 if not exists(select 1 from public.drivers where id=p_driver_id) then return false; end if;
 insert into public.attendance_links(driver_id,token_hash,expires_at,revoked_at,created_at)
 values(p_driver_id,p_token_hash,p_expires_at,null,now())
 on conflict(driver_id) do update set token_hash=excluded.token_hash,expires_at=excluded.expires_at,revoked_at=null,created_at=now();
 return true;
end; $$;
create or replace function public.admin_revoke_attendance_link(p_driver_id uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
 if not public.is_admin() then return false; end if;
 update public.attendance_links set revoked_at=now() where driver_id=p_driver_id and revoked_at is null;
 return found;
end; $$;
create or replace function public.attendance_for_token(p_token_hash text)
returns table(driver_name text,race_id uuid,round int,race_name text,track text,race_date date,choice text)
language plpgsql security definer set search_path = '' stable as $$
declare v_driver_id uuid;
begin
 if p_token_hash !~ '^[a-f0-9]{64}$' then return; end if;
 select l.driver_id into v_driver_id from public.attendance_links l
 where l.token_hash=p_token_hash and l.revoked_at is null and l.expires_at > now();
 if v_driver_id is null then return; end if;
 return query select d.name,r.id,r.round,r.name,r.track,r.race_date,e.choice
 from public.drivers d cross join public.races r
 left join public.attendance_entries e on e.race_id=r.id and e.driver_id=d.id
 where d.id=v_driver_id and not exists(select 1 from public.results z where z.race_id=r.id)
 order by r.round;
end; $$;
create or replace function public.attendance_submit(p_token_hash text,p_race_id uuid,p_choice text)
returns boolean language plpgsql security definer set search_path = '' as $$
declare v_driver_id uuid;
begin
 if p_token_hash !~ '^[a-f0-9]{64}$' or p_choice not in ('yes','maybe','no') then return false; end if;
 select l.driver_id into v_driver_id from public.attendance_links l
 where l.token_hash=p_token_hash and l.revoked_at is null and l.expires_at>now();
 if v_driver_id is null then return false; end if;
 if not exists(select 1 from public.races r where r.id=p_race_id and not exists(select 1 from public.results z where z.race_id=r.id)) then return false; end if;
 insert into public.attendance_entries(race_id,driver_id,choice,updated_at)
 values(p_race_id,v_driver_id,p_choice,now())
 on conflict(race_id,driver_id) do update set choice=excluded.choice,updated_at=now();
 return true;
end; $$;
create or replace function public.attendance_overview()
returns table(race_id uuid,yes_count bigint,maybe_count bigint,no_count bigint)
language sql security definer set search_path = '' stable as $$
 select r.id,count(*) filter(where e.choice='yes'),count(*) filter(where e.choice='maybe'),count(*) filter(where e.choice='no')
 from public.races r left join public.attendance_entries e on e.race_id=r.id group by r.id;
$$;

